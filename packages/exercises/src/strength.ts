function deriveStress(entry: RawEntry): JointStress {
  return STRESS_OVERRIDES[entry.id] ?? PATTERN_STRESS[entry.pattern] ?? s(0, 0, 0)
}

/** Passos em formato de lista simples, para quem ainda lê `cues` (planos e prompts). */
function cuesFromGuidance(g: Guidance): string[] {
  return [...g.setup, ...g.steps, ...(g.commonError ? [`Erro comum: ${g.commonError}`] : [])]
}

type FieldSource = Pick<RawEntry, 'muscleGroup' | 'pattern' | 'cues' | 'muscles' | 'guidance'>

/**
 * `cues` e `muscles` efetivos. Pendente: valores atuais (derivados), para nada mudar antes da aprovação.
 * Aprovado: `cues` vem da orientação e `muscles` é o explícito do registro (data-model).
 */
export function effectiveFields(entry: FieldSource, pending: boolean): { cues: string[]; muscles: Muscles } {
  if (pending) return { cues: entry.cues, muscles: deriveMuscles(entry) }
  return {
    cues: entry.guidance ? cuesFromGuidance(entry.guidance) : entry.cues,
    muscles: entry.muscles ?? deriveMuscles(entry),
  }
}

export const STRENGTH_EXERCISES: StrengthExercise[] = RAW_ENTRIES.map((entry) => ({
  ...entry,
  kind: 'forca' as const,
  ...effectiveFields(entry, PENDING_IDS.has(entry.id)),
  tempo: deriveTempo(entry),
  stress: deriveStress(entry),
}))

const BY_ID = new Map(STRENGTH_EXERCISES.map((e) => [e.id, e]))
const BY_NAME = new Map(STRENGTH_EXERCISES.map((e) => [e.name, e]))

/** Exercício de força pelo id ou pelo nome exato. */
export function findStrengthExercise(idOrName: string): StrengthExercise | undefined {
  return BY_ID.get(idOrName) ?? BY_NAME.get(idOrName)
}
